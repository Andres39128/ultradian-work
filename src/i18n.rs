#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_i18n_keys_non_empty() {
        let keys = [
            "settings_screen",
            "screen_dim_during_rest",
            "screen_lock_during_rest",
            "breathe_in",
            "breathe_out",
            "rest_message",
            "delete_project_confirm",
            "screen_available",
            "screen_not_available",
            "wayland_warning",
            "ultradian_project",
            "date_unix",
            "exported_to",
            "error_export",
            "error_open_file",
            "sheet_not_found",
            "imported_tasks",
            "excel_header_name",
            "excel_header_description",
            "excel_header_project",
            "excel_header_completed",
            "excel_header_priority",
            "excel_header_tags",
            "excel_header_deadline",
            "none",
            "chart_projects",
        ];
        for key in keys {
            let en = t(&Language::En, key);
            let es = t(&Language::Es, key);
            assert!(!en.is_empty(), "Missing EN translation for {}", key);
            assert!(!es.is_empty(), "Missing ES translation for {}", key);
        }
    }
}
